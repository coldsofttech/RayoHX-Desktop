"""Build script. With PYD_BUILD=1 the whole rayohx_desktop package is compiled by Nuitka into one
extension module (rayohx_desktop.pyd on Windows, rayohx_desktop.so elsewhere) and no .py source is
left in the wheel. Beside the binary a rayohx_desktop/ folder (no __init__.py, so Python loads the
binary, not the folder) holds the .pyi type stubs generated by mypy's stubgen and, in assets/, the
built front end (ui/dist), which a single binary cannot carry. Without PYD_BUILD the package builds
as plain Python, so local development, editable installs and coverage are unaffected.
`python -m rayohx_desktop` does not work on the compiled build (__main__ is embedded in the binary);
the `rayohxd` command does.
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

from setuptools import Extension, setup
from setuptools.command.build_ext import build_ext as _build_ext

COMPILE = os.environ.get("PYD_BUILD") == "1"
NAME = "rayohx_desktop"
OUT = Path("build/nuitka")
STUBS = Path("build/stubs")


class build_ext(_build_ext):
    def build_extension(self, ext):  # type: ignore[no-untyped-def]
        # Drop anything an earlier build left behind in the wheel staging dir.
        shutil.rmtree(self.build_lib, ignore_errors=True)
        shutil.rmtree(OUT, ignore_errors=True)
        shutil.rmtree(STUBS, ignore_errors=True)
        subprocess.run(  # noqa: S603
            [
                sys.executable,
                "-m",
                "nuitka",
                "--module",
                f"src/{NAME}",
                f"--include-package={NAME}",
                f"--output-dir={OUT}",
                "--assume-yes-for-downloads",
                "--remove-output",
            ],
            check=True,
        )
        binary = next(p for p in OUT.glob(f"{NAME}.*") if p.suffix in {".pyd", ".so"})
        target = Path(self.get_ext_fullpath(ext.name))
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(binary, target)

        from mypy.stubgen import main as stubgen

        stubgen(["-o", str(STUBS), f"src/{NAME}"])
        shutil.copytree(STUBS / NAME, target.parent / NAME, dirs_exist_ok=True)
        (target.parent / NAME / "py.typed").touch()

        dist = Path(f"src/{NAME}/ui/dist")
        if dist.is_dir():  # built by `npm run build`; a wheel without it has no front end
            shutil.copytree(dist, target.parent / NAME / "assets", dirs_exist_ok=True)


if COMPILE:
    setup(
        packages=[],
        package_data={},
        ext_modules=[Extension(NAME, sources=[])],
        cmdclass={"build_ext": build_ext},
    )
else:
    setup()
